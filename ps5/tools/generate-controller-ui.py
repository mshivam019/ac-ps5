#!/usr/bin/env python3
"""Render original vector prompts; optionally verify hashes against an owned USA rev-0 ISO.

Requires rsvg-convert, ImageMagick (magick), and libxxhash for --verify-iso.
No disc pixels are written. DDS is uncompressed RGBA, top row first, just like
pc_gx_texture.c's GC decoder. The renderer must not flip these images.
"""
import argparse
import ctypes
import ctypes.util
import json
from pathlib import Path
import struct
import subprocess

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / 'ps5/assets/controller-ui'


def read_rel(iso):
    with iso.open('rb') as stream:
        header = stream.read(0x460)
        if header[:6] != b'GAFE01' or header[7] != 0:
            raise ValueError('Expected owned GAFE01 revision 0 ISO')
        offset, size = struct.unpack_from('>II', header, 0x424)
        stream.seek(offset)
        fst = stream.read(size)
        count = struct.unpack_from('>I', fst, 8)[0]
        strings = fst[count * 12:]
        for index in range(1, count):
            name, offset, size = struct.unpack_from('>III', fst, index * 12)
            if not name >> 24 and strings[name:strings.find(b'\0', name)] == b'foresta.rel.szs':
                stream.seek(offset)
                encoded = stream.read(size)
                break
        else:
            raise ValueError('foresta.rel.szs missing')
    if encoded[:4] != b'Yaz0':
        raise ValueError('Expected Yaz0 REL')
    size = struct.unpack_from('>I', encoded, 4)[0]
    result = bytearray()
    pos = 16
    while len(result) < size:
        flags = encoded[pos]
        pos += 1
        for bit in range(7, -1, -1):
            if len(result) == size:
                break
            if flags & (1 << bit):
                result.append(encoded[pos])
                pos += 1
            else:
                a, b = encoded[pos:pos + 2]
                pos += 2
                distance = ((a & 15) << 8 | b) + 1
                length = (a >> 4) + 2
                if a >> 4 == 0:
                    length = encoded[pos] + 18
                    pos += 1
                if distance > len(result) or len(result) + length > size:
                    raise ValueError('Invalid Yaz0 back reference')
                for _ in range(length):
                    result.append(result[-distance])
    return result


def verify(manifest, iso):
    rel = read_rel(iso)
    lib = ctypes.CDLL(ctypes.util.find_library('xxhash'))
    lib.XXH64.argtypes = [ctypes.c_void_p, ctypes.c_size_t, ctypes.c_ulonglong]
    lib.XXH64.restype = ctypes.c_ulonglong
    for entry in manifest['textures']:
        data = bytes(rel[int(entry['rel_offset'], 16):][:entry['bytes']])
        actual = f'{lib.XXH64(data, len(data), 0):016x}'
        if actual != entry['hash']:
            raise ValueError(f"Hash mismatch: {entry['source']}")
    print(f"Verified {len(manifest['textures'])} source hashes against owned disc")


def dds(width, height, pixels):
    assert len(pixels) == width * height * 4
    # Legacy DDS with explicit RGBA byte masks, one level, no vertical flip.
    header = [124, 0x100f, height, width, width * 4, 0, 0] + [0] * 11
    header += [32, 0x41, 0, 32, 0xff, 0xff00, 0xff0000, 0xff000000]
    header += [0x1000, 0, 0, 0, 0]
    return b'DDS ' + struct.pack('<31I', *header) + pixels


def render(svg, width, height):
    png = subprocess.run(['rsvg-convert', '-w', str(width), '-h', str(height), str(svg)],
                         check=True, capture_output=True).stdout
    # Force straight RGBA bytes even on ImageMagick Q16/HDRI installations.
    return subprocess.run(['magick', 'png:-', '-depth', '8', 'rgba:-'], input=png,
                          check=True, capture_output=True).stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--verify-iso', type=Path)
    parser.add_argument('--output', type=Path, default=ASSETS)
    args = parser.parse_args()
    manifest = json.loads((ASSETS / 'manifest.json').read_text())
    if args.verify_iso:
        verify(manifest, args.verify_iso)
    args.output.mkdir(parents=True, exist_ok=True)
    lines = ['/* Generated by ps5/tools/generate-controller-ui.py; no original pixels. */']
    seen = set()
    for entry in manifest['textures']:
        key = (entry['hash'], entry['width'], entry['height'], entry['format'])
        if key in seen:
            continue
        seen.add(key)
        w, h = entry['width'] * 4, entry['height'] * 4
        pixels = render(ASSETS / entry['svg'], w, h)
        name = f"tex1_{entry['width']}x{entry['height']}_{entry['hash']}_{entry['format']}.dds"
        (args.output / name).write_bytes(dds(w, h, pixels))
        lines.append('    { 0x%sULL, %d, %d, %d, "%s", 0, 0 },' %
                     (entry['hash'], entry['width'], entry['height'], entry['format'], name))
    (args.output / 'controller_ui.inc').write_text('\n'.join(lines) + '\n')
    # Standalone symbols are provided for future source-confirmed Z/C-stick paths.
    for symbol in ('r1', 'right-stick'):
        (args.output / f'{symbol}.dds').write_bytes(dds(128, 128, render(ASSETS / f'{symbol}.svg', 128, 128)))
    print(f'Generated {len(seen)} hash replacements and 2 unbound symbols')


if __name__ == '__main__':
    main()
